import { afterEach, describe, expect, it } from 'vitest'
import { startVulnerableLab } from './fixtures/vulnerable-lab.ts'

const labs: Awaited<ReturnType<typeof startVulnerableLab>>[] = []
afterEach(async () => { await Promise.all(labs.splice(0).map(lab => lab.close())) })
async function start(fixed = false) { const lab = await startVulnerableLab({ fixed }); labs.push(lab); return lab }

describe('local investigation target', () => {
  it('binds only loopback and exposes discoverable synthetic secrets without authentication', async () => {
    const { origin } = await start()
    expect(new URL(origin).hostname).toBe('127.0.0.1')
    const home = await (await fetch(origin)).text()
    expect(home).toContain('ProjectDesk')
    expect(home).toContain('/api/projects')
    const robots = await (await fetch(`${origin}/robots.txt`)).text()
    expect(robots).toContain('/debug/config'); expect(robots).toContain('/api/admin/export')
    const config = await fetch(`${origin}/debug/config`)
    expect(config.status).toBe(200)
    expect(await config.json()).toMatchObject({ API_SECRET: 'test_projectdesk_api_secret_7f39c2', DATABASE_URL: 'postgresql://lab-only:lab-only-db-password@database.invalid/projectdesk' })
    const exported = await fetch(`${origin}/api/admin/export`)
    expect(exported.status).toBe(200)
    expect(await exported.json()).toMatchObject({ users: [{ email: 'admin@projectdesk.invalid', role: 'admin', resetToken: 'test_reset_admin_74a9' }, { email: 'member@projectdesk.invalid', role: 'member' }] })
  })
  it('removes configuration disclosure and requires authentication after the repair', async () => {
    const { origin } = await start(true)
    const config = await fetch(`${origin}/debug/config`)
    expect(config.status).toBe(404); expect(await config.text()).not.toContain('API_SECRET')
    const exported = await fetch(`${origin}/api/admin/export`)
    expect(exported.status).toBe(401); expect(await exported.text()).not.toContain('resetToken')
    expect(await (await fetch(`${origin}/health`)).json()).toEqual({ status: 'ok', service: 'projectdesk' })
    expect(await (await fetch(`${origin}/api/projects`)).json()).toMatchObject({ projects: [{ id: 'lab-project-1' }] })
  })
  it('serves HEAD without a body and rejects writes and unknown paths', async () => {
    const { origin } = await start()
    const head = await fetch(`${origin}/debug/config`, { method: 'HEAD' })
    expect(head.status).toBe(200); expect(await head.text()).toBe('')
    const write = await fetch(`${origin}/api/admin/export`, { method: 'POST' })
    expect(write.status).toBe(405); expect(write.headers.get('allow')).toBe('GET, HEAD')
    expect((await fetch(`${origin}/missing`)).status).toBe(404)
  })
  it('can rebind the configured port for a repaired retest', async () => {
    const first = await startVulnerableLab()
    const port = Number(new URL(first.origin).port)
    await first.close()
    const repaired = await startVulnerableLab({ port, fixed: true }); labs.push(repaired)
    expect(repaired.origin).toBe(first.origin)
    expect((await fetch(`${repaired.origin}/debug/config`)).status).toBe(404)
  })
  it('discovers a query-based cross-customer disclosure and a read-only POST search', async () => {
    const lab = await startVulnerableLab({ toolScenario: true }); labs.push(lab)
    const home = await (await fetch(lab.origin)).text()
    expect(home).toContain('href="/billing"')
    const documentation = await (await fetch(`${lab.origin}/billing`)).text()
    expect(documentation).toContain('/api/invoices?id=lab-invoice-1')
    expect(documentation).toContain('POST /api/invoices/search')
    const own: unknown = await (await fetch(`${lab.origin}/api/invoices?id=lab-invoice-1`)).json()
    expect(own).toMatchObject({ customerId: 'lab-customer-1' })
    const other: unknown = await (await fetch(`${lab.origin}/api/invoices?id=lab-invoice-2`)).json()
    expect(other).toMatchObject({ customerId: 'lab-customer-2', privateNote: 'test_private_billing_note_82b1' })
    const search = await fetch(`${lab.origin}/api/invoices/search`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ customerId: 'lab-customer-2' }) })
    expect(search.status).toBe(200)
    expect(await search.json()).toMatchObject({ invoices: [{ id: 'lab-invoice-2', privateNote: 'test_private_billing_note_82b1' }] })
    expect((await fetch(`${lab.origin}/api/invoices`)).status).toBe(404)
    expect((await fetch(`${lab.origin}/api/invoices/search`, { method: 'POST', body: 'invalid' })).status).toBe(400)
  })
  it('removes the multi-tool disclosure after repair while retaining the customer own invoice', async () => {
    const lab = await startVulnerableLab({ toolScenario: true, fixed: true }); labs.push(lab)
    expect((await fetch(`${lab.origin}/api/invoices?id=lab-invoice-1`)).status).toBe(200)
    const other = await fetch(`${lab.origin}/api/invoices?id=lab-invoice-2`)
    expect(other.status).toBe(403); expect(await other.text()).not.toContain('test_private_billing_note')
    const search = await fetch(`${lab.origin}/api/invoices/search`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ customerId: 'lab-customer-2' }) })
    expect(search.status).toBe(403); expect(await search.text()).not.toContain('test_private_billing_note')
  })
  it('does not enable tool investigation endpoints for existing lab callers', async () => {
    const { origin } = await start()
    expect(await (await fetch(origin)).text()).not.toContain('/billing')
    expect((await fetch(`${origin}/billing`)).status).toBe(404)
    expect((await fetch(`${origin}/api/invoices?id=lab-invoice-2`)).status).toBe(404)
    expect((await fetch(`${origin}/api/invoices/search`, { method: 'POST', body: '{}' })).status).toBe(405)
  })
})
